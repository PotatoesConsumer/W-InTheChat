/**
 * chatMessage.js
 *
 * Outbound contract: the chat messages the service sends to the UI.
 * Spec: docs/events.md ("Chat messages").
 *
 * Streaming: a message arrives as several updates with the same `id`. Each
 * update carries the full text so far (not a delta), so the UI just replaces it,
 * and a dropped update can't garble the line. The last update has `done: true`.
 */

import { SCHEMA_VERSION, LIMITS, EventValidationError, isPlainObject } from "./schema.js";

export const PERSONAS = Object.freeze(["fan", "hater", "backseat", "lurker"]);

/**
 * Where the text came from. Logged for the evaluation, which reports AI, scripted
 * and fallback output separately.
 *   ai: generated by the model and passed the output filter
 *   template: a routine template (minor events)
 *   scripted: the scripted-chat baseline condition
 *   fallback: safe template used because generation was rejected or timed out
 */
export const MESSAGE_SOURCES = Object.freeze(["ai", "template", "scripted", "fallback"]);

export const MESSAGE_LIMITS = Object.freeze({
  maxTextLength: 200,
  maxViewerLength: 25,
});

const FIELDS = new Set(["v", "id", "kind", "ts", "eventId", "persona", "viewer", "source", "text", "done"]);

/**
 * @param {object} fields
 * @param {string|null} [fields.eventId] - The event this replies to, or null for ambient chat.
 * @param {string} fields.persona - One of PERSONAS.
 * @param {string} fields.viewer - Display name shown in chat.
 * @param {string} fields.source - One of MESSAGE_SOURCES.
 * @param {string} fields.text - Full text so far.
 * @param {boolean} [fields.done] - False while a streamed message is still growing.
 * @param {string} [fields.id] - Reuse the same id for every update of one message.
 * @param {number} [fields.ts]
 * @returns {Readonly<object>} a frozen, validated chat message
 * @throws {EventValidationError}
 */
export function createChatMessage({
  eventId = null,
  persona,
  viewer,
  source,
  text,
  done = true,
  id = globalThis.crypto.randomUUID(),
  ts = Date.now(),
}) {
  const message = { v: SCHEMA_VERSION, id, kind: "chat_message", ts, eventId, persona, viewer, source, text, done };
  const result = validateChatMessage(message);
  if (!result.ok) throw new EventValidationError(result.errors, "chat message");
  return Object.freeze(message);
}

/**
 * @param {unknown} message
 * @returns {{ok: true} | {ok: false, errors: {path: string, message: string}[]}}
 */
export function validateChatMessage(message) {
  const errors = [];
  const fail = (path, msg) => errors.push({ path, message: msg });

  if (!isPlainObject(message)) {
    fail("", "chat message must be a plain object");
    return { ok: false, errors };
  }

  for (const key of Object.keys(message)) {
    if (!FIELDS.has(key)) fail(key, "unknown field for kind \"chat_message\"");
  }

  if (message.v !== SCHEMA_VERSION) fail("v", `unsupported schema version ${message.v}`);
  if (message.kind !== "chat_message") fail("kind", "must be \"chat_message\"");
  checkId(message.id, "id", fail);
  if (message.eventId !== null) checkId(message.eventId, "eventId", fail);

  if (!Number.isSafeInteger(message.ts) || message.ts < 0) {
    fail("ts", "must be a non-negative integer (ms since epoch)");
  }
  if (!PERSONAS.includes(message.persona)) fail("persona", `must be one of ${PERSONAS.join(", ")}`);
  if (!MESSAGE_SOURCES.includes(message.source)) {
    fail("source", `must be one of ${MESSAGE_SOURCES.join(", ")}`);
  }

  if (typeof message.viewer !== "string" || message.viewer.trim().length === 0) {
    fail("viewer", "must be a non-empty string");
  } else if (message.viewer.length > MESSAGE_LIMITS.maxViewerLength) {
    fail("viewer", `must be at most ${MESSAGE_LIMITS.maxViewerLength} characters`);
  }

  if (typeof message.text !== "string" || message.text.trim().length === 0) {
    fail("text", "must be a non-empty string");
  } else if (message.text.length > MESSAGE_LIMITS.maxTextLength) {
    fail("text", `must be at most ${MESSAGE_LIMITS.maxTextLength} characters`);
  }

  if (typeof message.done !== "boolean") fail("done", "must be a boolean");

  return errors.length === 0 ? { ok: true } : { ok: false, errors };
}

function checkId(value, path, fail) {
  if (typeof value !== "string" || value.length === 0) {
    fail(path, "must be a non-empty string");
  } else if (value.length > LIMITS.maxIdLength) {
    fail(path, `must be at most ${LIMITS.maxIdLength} characters`);
  }
}
